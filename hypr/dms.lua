-- Entry point: Hyprland + DankMaterialShell.
-- Launched by /usr/local/share/wayland-sessions/hyprland-dms.desktop
-- Everything except the shell layer is shared with hyprland.lua via common.lua.
--
-- DMS brings its own bar, notifications, tray, wallpaper, lock screen, idle
-- handling and polkit agent, so swaync/waybar/hyprpaper/hypridle/polkit-mate
-- are not started here, and any left over from a waybar session are swept
-- first (they would otherwise hold org.freedesktop.Notifications / the tray).
--
-- DMS is started here rather than via its systemd user unit on purpose: the
-- unit is bound to graphical-session.target and would also start in the
-- waybar session.
--
-- The [p] in the polkit pattern keeps `pkill -f` from matching (and killing)
-- the shell running this very line, which would abort before `dms run`.

local common  = require("common")
local mainMod = common.mainMod

-- Generated by DMS (theme colours, gaps/rounding, its window rules); loaded
-- after common.lua so they override it.
require("dms.colors")
require("dms.layout")
require("dms.windowrules")

common.autostart({
    "pkill -x swaync; pkill -x mako; pkill -x waybar; pkill -x hyprpaper; pkill -x hypridle; pkill -f '[p]olkit-mate-authentication-agent'; dms run",
})

hl.bind(mainMod .. " + R",       hl.dsp.exec_cmd("dms ipc call spotlight toggle"),     { description = "App launcher" })
hl.bind(mainMod .. " + X",       hl.dsp.exec_cmd("dms ipc call powermenu toggle"),     { description = "Power menu" })
hl.bind(mainMod .. " + N",       hl.dsp.exec_cmd("dms ipc call notifications toggle"), { description = "Notification center" })
hl.bind(mainMod .. " + comma",   hl.dsp.exec_cmd("dms ipc call settings toggle"),      { description = "DMS settings" })
hl.bind(mainMod .. " + ALT + L", hl.dsp.exec_cmd("dms ipc call lock lock"),            { description = "Lock screen" })
